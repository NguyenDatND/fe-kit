import { createHash, randomBytes } from 'node:crypto'
import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { draftsAreReady, draftsDir } from './drafts.mjs'
import { UsageError } from './errors.mjs'
import { runCommand, runFile, shellQuote, succeeded } from './exec.mjs'
import { exists, lstatOrNull } from './fsx.mjs'
import { toPosix } from './glob.mjs'
import { expandGlobs } from './walk.mjs'

const LOCAL_TESTS = '.fe-kit/tests'
const TEST_FILES = '**/*.{test,spec}.{js,jsx,ts,tsx,mjs,cjs,mts,cts}'
// For a jest configuration that selects tests by testRegex: jest refuses a testMatch next to it.
const LOCAL_TESTS_REGEX = String.raw`[/\\]\.fe-kit[/\\]tests[/\\].*\.(?:test|spec)\.[cm]?[jt]sx?$`
const JEST_CONFIG_TIMEOUT_MS = 60_000
// What the overlay stops with when the vitest configuration has projects, and what is looked for in the output of that run.
const PROJECTS_MARKER = 'fe-kit: vitest projects are not supported by local tests yet'
export const PROJECTS_SKIP = 'vitest projects (a workspace) are not supported by local tests yet'
const OVERLAY = 'vitest.overlay.config.mjs'
// The order vitest itself looks in: its own config wins over the build tool's.
const BASE_CONFIGS = ['vitest.config', 'vite.config'].flatMap((name) => ['ts', 'mts', 'cts', 'js', 'mjs', 'cjs'].map((extension) => `${name}.${extension}`))

/** The test files the project keeps under `.fe-kit/tests`, as sorted project-relative paths. */
export async function findLocalTests(projectRoot) {
  const { files, unreadable } = await expandGlobs(projectRoot, [`${LOCAL_TESTS}/${TEST_FILES}`])
  if (unreadable.length > 0) {
    // Tests in a folder that cannot be read would not run, and "no local tests" would be a wrong thing to say about it.
    throw new UsageError(`cannot read ${unreadable.map(({ path, code }) => `${path} (${code})`).join(', ')}, so the local tests in it cannot run`)
  }
  return files
}

async function findBaseConfig(packageRoot) {
  for (const name of BASE_CONFIGS) {
    if (await exists(join(packageRoot, name))) return join(packageRoot, name)
  }
  return null
}

/** The project's own binary, searched where its package manager would put it: the package, then up to the project root. */
async function findBinary(name, packageRoot, projectRoot) {
  for (let directory = packageRoot; ; directory = dirname(directory)) {
    const candidate = join(directory, 'node_modules', '.bin', name)
    if (await exists(candidate)) return candidate
    if (directory === projectRoot || dirname(directory) === directory) return null
  }
}

/**
 * The project's own vitest config with one thing changed: which tests run. `include` is replaced, not merged: merging
 * (`mergeConfig`) concatenates arrays, so a project that lists its own `include` would run its own tests as well.
 * `dir` is set to the package because `include` is relative to it, and a project may set `dir: 'src'` or a `root`
 * of its own, which would make `include` find nothing. A
 * configuration with `projects` (or the older `workspace`) runs its own projects whatever `include` says, so the overlay
 * stops there and the step is skipped.
 */
function overlaySource({ baseImport, include, resolveFrom, dir }) {
  const lines = ["// Generated by `fe-kit test`: the project's own config, with only the tests that run replaced. Safe to delete."]
  if (baseImport !== null) lines.push(`import base from ${JSON.stringify(baseImport)}`)
  if (resolveFrom) {
    // `.fe-kit` is at the project root, above the package, and has no node_modules: what a local test imports by name
    // has to be looked up from the package instead.
    lines.push(
      '',
      'const fromPackage = {',
      "  name: 'fe-kit-resolve-from-package',",
      "  enforce: 'pre',",
      '  resolveId(source, importer, options) {',
      `    if (!importer || !importer.startsWith(${JSON.stringify(resolveFrom.drafts)}) || /^[./]/.test(source)) return null`,
      `    return this.resolve(source, ${JSON.stringify(resolveFrom.importer)}, { ...options, skipSelf: true })`,
      '  },',
      '}',
    )
  }
  // `passWithNoTests: false` whatever the project says: a run that found none of the drafts (its `exclude` names `.fe-kit`, say) has not passed.
  const tests = `test: { include: ${JSON.stringify(include)}, passWithNoTests: false }`
  if (baseImport === null) {
    lines.push('', `export default { ${resolveFrom ? 'plugins: [fromPackage], ' : ''}${tests} }`)
  } else {
    const plugins = resolveFrom ? ', plugins: [...(resolved.plugins ?? []), fromPackage]' : ''
    lines.push(
      '',
      'export default async (env) => {',
      "  const resolved = typeof base === 'function' ? await base(env) : await base",
      `  if (resolved.test?.projects || resolved.test?.workspace) throw new Error(${JSON.stringify(PROJECTS_MARKER)})`,
      `  return { ...resolved${plugins}, test: { ...resolved.test, dir: ${JSON.stringify(dir)}, include: ${JSON.stringify(include)}, passWithNoTests: false } }`,
      '}',
    )
  }
  return `${lines.join('\n')}\n`
}

/** Each package has its own overlay file, so two runs in different packages at the same time do not overwrite each other's. */
const overlayName = (projectRoot, packageRoot) =>
  packageRoot === projectRoot ? OVERLAY : OVERLAY.replace('.config', `.${createHash('sha1').update(toPosix(relative(projectRoot, packageRoot))).digest('hex').slice(0, 8)}.config`)

/** Writes the overlay into `.fe-kit/` (only when it changed) and returns its path. */
async function writeOverlay({ projectRoot, packageRoot }) {
  const drafts = draftsDir(projectRoot)
  const base = await findBaseConfig(packageRoot)
  const source = overlaySource({
    baseImport: base === null ? null : toPosix(relative(drafts, base)),
    include: [`${toPosix(relative(packageRoot, join(drafts, 'tests')))}/${TEST_FILES}`],
    dir: toPosix(packageRoot),
    resolveFrom: packageRoot === projectRoot ? null : { drafts: `${toPosix(drafts)}/`, importer: toPosix(join(packageRoot, 'package.json')) },
  })
  const path = join(drafts, overlayName(projectRoot, packageRoot))
  const existing = await lstatOrNull(path)
  // Writing to a link would write to whatever it points at: a file of the project, say.
  if (existing && !existing.isFile()) throw new UsageError(`${toPosix(relative(projectRoot, path))} is not a regular file; remove it so that fe-kit can generate it`)
  if ((await readFile(path, 'utf8').catch(() => null)) !== source) {
    try {
      // A new file replaces the old one (renamed over it), so a hard link to a file of the project is never written through
      // and a run that reads the overlay never sees half of one.
      const staging = `${path}.${process.pid}-${randomBytes(4).toString('hex')}.tmp`
      try {
        await writeFile(staging, source, { flag: 'wx' })
        await rename(staging, path)
      } catch (failure) {
        await rm(staging, { force: true })
        throw failure
      }
    } catch (error) {
      // A read-only workspace is a place where the local tests cannot run, not a crash.
      throw new UsageError(`could not write ${toPosix(relative(projectRoot, path))} (${error.code ?? error.message}), which the local tests need`)
    }
  }
  return path
}

/** The JSON object in a program's output, which may have lines of its own around it (a banner, a warning); null when there is none. */
export function extractJson(text) {
  const start = text.search(/^\{/m)
  const end = text.lastIndexOf('}')
  if (start === -1 || end < start) return null
  try {
    return JSON.parse(text.slice(start, end + 1))
  } catch {
    return null
  }
}

// `--coverage.enabled=false`: a coverage threshold of the project would fail a run of three drafts.
function planVitest({ packageRoot }, overlay, filters) {
  const args = ['run', '--config', overlay, '--coverage.enabled=false', ...filters]
  return { args, command: ['vitest', 'run', '--config', toPosix(relative(packageRoot, overlay)), '--coverage.enabled=false', ...filters].join(' ') }
}

/** The one jest configuration the project has, as `jest --showConfig` prints it (every path in it already expanded). */
async function readJestConfig(binary, packageRoot, { env, timeoutMs, graceMs }) {
  const shown = await runFile(binary, ['--showConfig'], { cwd: packageRoot, env, stderr: 'discard', timeoutMs: Math.min(timeoutMs ?? JEST_CONFIG_TIMEOUT_MS, JEST_CONFIG_TIMEOUT_MS), graceMs })
  const configs = succeeded(shown) ? extractJson(shown.output)?.configs : null
  if (!Array.isArray(configs) || configs.length === 0) throw new UsageError('could not read the jest configuration: `jest --showConfig` did not print one')
  if (configs.length > 1) throw new UsageError('this jest configuration has several projects (`projects`), which local tests do not support yet')
  return configs[0]
}

/**
 * Jest has no way to be told "the same configuration, other tests", so the call is built from what the configuration
 * says: its own roots (they carry `__mocks__`) plus `.fe-kit/tests`, and a test match that names only the local tests.
 * Filters go first: a flag that takes a list swallows every word after it. `--coverage=false` because a coverage
 * threshold of the project would fail a run of three drafts. Measured with jest 30.5.2 and 29.7.0.
 */
async function planJest({ projectRoot, packageRoot }, binary, filters, limits) {
  const config = await readJestConfig(binary, packageRoot, limits)
  const localRoot = join(draftsDir(projectRoot), 'tests')
  const select = config.testRegex?.length > 0 ? `--testRegex=${LOCAL_TESTS_REGEX}` : `--testMatch=<rootDir>/${toPosix(relative(config.rootDir ?? packageRoot, localRoot))}/${TEST_FILES}`
  const roots = [...(config.roots ?? []), localRoot]
  const args = [...filters, ...roots.map((root) => `--roots=${root}`), select, '--coverage=false']
  const shown = [...filters, ...roots.map((root) => `--roots=${toPosix(relative(packageRoot, root)) || '.'}`), select, '--coverage=false']
  return { args, command: ['jest', ...shown].join(' ') }
}

/**
 * Runs the tests in `.fe-kit/tests` with the project's own test runner (vitest or jest), from the package that has it.
 * Resolves `{ status: 'skipped', reason }` when there are none, else `{ status: 'ran', runner, command, files, passed, ...result }`
 * (see runFile for the result; a run that had to be stopped, or could not start, has not passed). Throws UsageError when
 * the project cannot run them: no `.fe-kit` set up, no supported runner, or one that is not installed.
 */
export async function runLocalTests(project, { filters = [], env, timeoutMs, graceMs } = {}) {
  const { projectRoot, packageRoot, stack } = project
  const option = filters.find((filter) => filter.startsWith('-'))
  if (option !== undefined) {
    throw new UsageError(`"${option}" looks like an option of the test runner; fe-kit test takes file filters only (write ./${option} for a file whose name starts with a dash)`)
  }
  const files = await findLocalTests(projectRoot)
  if (files.length === 0) return { status: 'skipped', reason: `no local tests in ${LOCAL_TESTS}` }

  if (!(await draftsAreReady(projectRoot))) {
    throw new UsageError('.fe-kit is not set up here (a real folder whose .gitignore hides everything in it), so a generated file could show up in git status or land elsewhere: run `fe-kit init` first')
  }
  const runner = stack.testRunner
  if (runner !== 'vitest' && runner !== 'jest') {
    throw new UsageError('local tests run with the vitest or jest of the project, and this project has neither in package.json; fe-kit does not add test libraries')
  }
  const binary = await findBinary(runner, packageRoot, projectRoot)
  if (binary === null) throw new UsageError(`${runner} is in package.json but not installed (no node_modules/.bin/${runner}): run the install of the package manager`)

  const limits = { env, timeoutMs, graceMs }
  const { args, command } = runner === 'jest' ? await planJest(project, binary, filters, limits) : planVitest(project, await writeOverlay(project), filters)
  const result = await runFile(binary, args, { cwd: packageRoot, ...limits })
  // The error as vitest prints it (`Error: <message>`), not the source line that throws it.
  if (runner === 'vitest' && result.exitCode !== 0 && result.output.includes(`Error: ${PROJECTS_MARKER}`)) return { status: 'skipped', reason: PROJECTS_SKIP }
  return { status: 'ran', runner, command, files, passed: succeeded(result), ...result }
}

// npm treats a flag it does not know after the script name as its own, so arguments for the script go after `--`.
// pnpm and yarn pass them on as they are, and pnpm would hand the `--` itself to the script (measured, not assumed).
const NPM_SCRIPT = /^npm\s+(?:run|run-script|test|t|tst)\b/
const PACKAGE_MANAGER_COMMAND = /^(?:npm|pnpm|yarn|bun)\s+(?:run(?:-script)?\s+)?(\S+)/

function appendArguments(command, args) {
  const words = args.map(shellQuote).join(' ')
  return NPM_SCRIPT.test(command) && !/\s--(?:\s|$)/.test(command) ? `${command} -- ${words}` : `${command} ${words}`
}

/** What a test command runs: the text of the package.json script it names, else the command itself (`pnpm vitest run`). */
function commandBody(command, scripts) {
  const name = PACKAGE_MANAGER_COMMAND.exec(command)?.[1]
  return (name && scripts[name]) || command
}

// Anchored at jest's rootDir: unanchored, a folder above the project with this name would hide every test.
const ANCHORED_FE_KIT = String.raw`<rootDir>[/\\]\.fe-kit[/\\]`

/**
 * The jest run of the project without `.fe-kit/tests`. A list given on the command line REPLACES the one in the
 * configuration, so the patterns in effect are read with `--showConfig`, through the test command itself (a script that
 * passes `--config=x` makes a bare `jest --showConfig` read another configuration), and handed back with one more.
 */
async function jestCommand(command, packageRoot, { env, timeoutMs, graceMs }) {
  // npm would run the pre and post hooks of the script for this extra run, a build step say: `--ignore-scripts` leaves them out.
  const probe = !NPM_SCRIPT.test(command) ? command : /\s--(?:\s|$)/.test(command) ? command.replace(/\s--(?=\s|$)/, ' --ignore-scripts --') : `${command} --ignore-scripts`
  const shown = await runCommand(appendArguments(probe, ['--showConfig']), { cwd: packageRoot, env, stderr: 'discard', timeoutMs: Math.min(timeoutMs ?? JEST_CONFIG_TIMEOUT_MS, JEST_CONFIG_TIMEOUT_MS), graceMs })
  const configs = succeeded(shown) ? extractJson(shown.output)?.configs : null
  if (!Array.isArray(configs) || configs.length === 0) {
    return { command, note: 'could not read the jest configuration through the test command, so it may also run the tests under .fe-kit/tests' }
  }
  if (configs.length > 1) return { command, note: 'this jest configuration has several projects (`projects`); fe-kit cannot keep .fe-kit/tests out of this run' }
  const ignored = Array.isArray(configs[0].testPathIgnorePatterns) ? configs[0].testPathIgnorePatterns.filter((pattern) => typeof pattern === 'string') : ['/node_modules/']
  return { command: appendArguments(command, [...ignored, ANCHORED_FE_KIT].map((pattern) => `--testPathIgnorePatterns=${pattern}`)) }
}

/** Whether a shell command line has more than one command in it (a redirection such as `2>&1` is not one). */
const hasOperators = (text) => /&&|\|\||[;|&\n]/.test(text.replace(/\d*[<>]&\d+|&>>?/g, ''))

/**
 * The test command of the project, changed to leave `.fe-kit` out. Both vitest and jest also collect the tests under
 * `.fe-kit/tests` (their globs match dot directories), and those belong to `fe-kit test`. `note` says when that could
 * not be done. A package below the project root is not looking at `.fe-kit`, so its run is left alone.
 */
export async function projectTestCommand({ projectRoot, packageRoot, stack, commands }, limits = {}) {
  const command = commands.test
  const runner = stack.testRunner
  if (!command || packageRoot !== projectRoot || (runner !== 'vitest' && runner !== 'jest')) return { command: command ?? null }
  const body = commandBody(command, stack.scripts)
  if (!new RegExp(`\\b${runner}\\b`).test(body)) {
    return { command, note: `could not tell that the test command runs ${runner}, so it may also run the tests under .fe-kit/tests` }
  }
  // Arguments given to a script go to its LAST command (`vitest run && node check.js --exclude` hands them to node);
  // the same goes for a command of the profile that has operators of its own.
  if (hasOperators(body) || hasOperators(command)) {
    return { command, note: `the test command runs several commands, so ${runner} cannot be handed an argument; it may also run the tests under .fe-kit/tests` }
  }
  if (runner === 'jest') return jestCommand(command, packageRoot, limits)
  return { command: appendArguments(command, ['--exclude', `${LOCAL_TESTS.split('/')[0]}/**`]) }
}
